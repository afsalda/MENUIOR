import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import assert from "node:assert/strict";
import { writeFile, readFile } from "node:fs/promises";
const base = "http://127.0.0.1:4175";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const results = [];
let original;
try {
  const owner = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce", serviceWorkers: "block" });
  const guest = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce", serviceWorkers: "block" });
  const page = await owner.newPage(), menu = await guest.newPage();
  const errors = [];
  for (const p of [page, menu]) p.on("pageerror", e => errors.push(e.message));
  await page.goto(base + "/?admin=1");
  await page.getByRole("link", { name: "Sign in with ChatGPT" }).click();
  await page.getByRole("heading", { name: "Your menu, in your hands." }).waitFor();
  await page.locator(".admin-dish").first().waitFor();
  original = await (await owner.request.get(base + "/api/admin/menu")).json();
  assert.equal((await guest.request.get(base + "/api/admin/menu")).status(), 403);
  assert.equal((await guest.request.patch(base + "/api/admin/items/iced-latte", { headers: { Origin: base }, data: { item: original.items[0], revision: original.revision } })).status(), 403);
  assert.equal((await owner.request.patch(base + "/api/admin/items/iced-latte", { headers: { Origin: "https://untrusted.example" }, data: { item: original.items[0], revision: original.revision } })).status(), 403);
  const bad = { ...original.items.find(i => i.id === "iced-latte"), price: -5 };
  assert.equal((await owner.request.patch(base + "/api/admin/items/iced-latte", { headers: { Origin: base }, data: { item: bad, revision: original.revision } })).status(), 400);
  await menu.goto(base + "/?table=5");
  await menu.getByRole("searchbox").fill("Iced Caramel Latte");
  await page.locator("#price-iced-latte").fill("205");
  await page.getByRole("button", { name: "Save price for Iced Caramel Latte" }).click();
  await expect(menu.locator(".card-bottom strong")).toHaveText("₹205", { timeout: 10000 });
  await page.getByRole("switch", { name: "Sold out: Iced Caramel Latte", exact: true }).click();
  await expect(menu.getByRole("button", { name: "Add Iced Caramel Latte", exact: true })).toBeDisabled({ timeout: 10000 });
  await page.getByRole("switch", { name: "Sold out: Iced Caramel Latte", exact: true }).click();
  await expect(menu.getByRole("button", { name: "Add Iced Caramel Latte", exact: true })).toBeEnabled({ timeout: 10000 });
  const stale = await owner.request.patch(base + "/api/admin/items/iced-latte", { headers: { Origin: base }, data: { item: original.items[0], revision: original.revision } });
  assert.equal(stale.status(), 409);
  results.push("Owner authentication, guest write denial, cross-origin denial, price validation and optimistic edit conflicts pass. Price and sold-out changes reach an independent guest browser within 10-second test budget (3-second refresh).");
  const row = page.locator(".admin-dish").filter({ has: page.getByRole("heading", { name: "Iced Caramel Latte", exact: true }) });
  await row.getByRole("button", { name: "Edit dish" }).click();
  await page.getByRole("button", { name: "हिन्दी", exact: true }).click();
  await page.getByLabel("Dish name · हिन्दी").fill("टेस्ट लाटे");
  await page.getByRole("button", { name: "English", exact: true }).click();
  await page.getByRole("checkbox", { name: "New", exact: true }).check();
  await page.getByRole("checkbox", { name: "Creamy Alfredo Pasta", exact: true }).check();
  await page.locator('input[type="file"]').setInputFiles("public/brand/demo/iced-coffee.webp");
  await expect(page.getByLabel("Photo URL")).toHaveValue(/\/media\/photos\//);
  await page.screenshot({ path: "qa/admin-editor-desktop.png" });
  await page.getByRole("button", { name: "Save dish", exact: true }).click();
  await expect(page.locator("dialog")).toHaveCount(0);
  await menu.getByRole("button", { name: "Iced Caramel Latte", exact: true }).click();
  await menu.locator(".item-drawer").waitFor();
  await expect(menu.locator(".item-drawer")).toContainText("Creamy Alfredo Pasta");
  await menu.keyboard.press("Escape");
  await page.getByRole("button", { name: "Dish views", exact: true }).click();
  await page.getByRole("button", { name: "Refresh views", exact: true }).click();
  await expect(page.locator(".analytics-row").filter({ hasText: "Iced Caramel Latte" }).locator("strong")).not.toHaveText("0");
  const viewBefore = await (await owner.request.get(base + "/api/admin/analytics")).json();
  await owner.request.post(base + "/api/views", { headers: { Origin: base }, data: { itemId: "iced-latte", eventId: crypto.randomUUID() } });
  const viewAfter = await (await owner.request.get(base + "/api/admin/analytics")).json();
  assert.deepEqual(viewBefore.dishes, viewAfter.dishes);
  results.push("Dish editor saves translations, tags, upsells and a real R2 photo upload. Guest detail opens appear in shared analytics; owner views are excluded.");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByLabel("Google review link", { exact: true }).fill("https://example.com/review-test");
  await page.getByRole("button", { name: "Save settings", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Settings saved");
  await menu.getByRole("searchbox").fill("");
  await menu.getByRole("link", { name: "Request bill", exact: true }).evaluate(a => a.addEventListener("click", e => e.preventDefault()));
  await menu.getByRole("link", { name: "Request bill", exact: true }).click();
  await expect(menu.getByRole("link", { name: "Rate us on Google" })).toHaveAttribute("href", "https://example.com/review-test", { timeout: 10000 });
  results.push("Review link edited in Settings reaches the guest menu and appears after Request bill. No live messages or reviews submitted.");
  for (const width of [1440, 768, 390, 360]) {
    await page.setViewportSize({ width, height: width > 700 ? 1000 : 844 });
    await page.getByRole("button", { name: "Menu items", exact: true }).click();
    await page.evaluate(() => scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `qa/admin-${width}.png` });
    const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
    results.push({ scope: `admin ${width}`, violations: audit.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) });
  }
  await menu.setViewportSize({ width: 390, height: 844 });
  await menu.reload();
  await menu.getByRole("searchbox").waitFor();
  await menu.evaluate(() => scrollTo(0, 0));
  await menu.screenshot({ path: "qa/glass-mobile-top.png" });
  await menu.locator("#section-new").scrollIntoViewIfNeeded();
  await menu.screenshot({ path: "qa/glass-mobile-products.png" });
  await menu.setViewportSize({ width: 1440, height: 1000 });
  await menu.evaluate(() => scrollTo(0, 0));
  await menu.screenshot({ path: "qa/glass-desktop-top.png" });
  await menu.locator("#section-new").screenshot({ path: "qa/glass-desktop-products.png" });
  assert.deepEqual(errors, []);
  assert.equal(results.filter(r => typeof r === "object").reduce((n, r) => n + r.violations.length, 0), 0);
  // Restore only local test content; never run this script against the hosted Site.
  const current = await (await owner.request.get(base + "/api/admin/menu")).json();
  const restored = await owner.request.patch(base + "/api/admin/items/iced-latte", { headers: { Origin: base }, data: { item: original.items.find(i => i.id === "iced-latte"), revision: current.revision } });
  const state = await restored.json();
  await owner.request.patch(base + "/api/admin/settings", { headers: { Origin: base }, data: { settings: original.settings, revision: state.revision } });
  console.log(JSON.stringify(results, null, 2));
} finally { await writeFile("qa/admin-results.json", JSON.stringify(results, null, 2)); await browser.close(); }
